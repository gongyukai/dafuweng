import { createRoom, addPlayer, startGame, act } from '../public/game/engine.js';
const room = createRoom('DBG');
room.missionsEnabled = false;
const a = addPlayer(room, 'A', { isBot: true }).player;
const b = addPlayer(room, 'B', { isBot: true }).player;
startGame(room);
room.turn = 0;
room.phase = 'roll';
room.owners[1] = b.id;
a.pos = 39;
a.forcedDice = 2;
console.log('turn', room.turn, 'cur', room.players[room.turn].name, 'phase', room.phase);
const r = act(room, a.id, { type: 'roll' });
console.log('act', r, 'phase', room.phase, 'pos', a.pos, 'cashA', a.cash, 'cashB', b.cash, 'rentB', b.rentIncome);
console.log(room.log.slice(-8).map((l) => l.kind + ': ' + l.text));
